def get_plural_cutlets(number: int) -> str:
    """
    Снайперский офис плюрализации.
    Хладнокровно подставляет правильное окончание к слову 'котлета'
    на основе остатка от деления числа на 10 и 100.
    """
    # Берем модуль числа на всякий случай
    n = abs(number)

    # Находим остатки от деления на 100 и на 10
    n100 = n % 100
    n10 = n % 10

    # 1. Жесткое исключение русского языка: от 11 до 14 всегда 'котлет' (11 котлет, 12 котлет)
    if 11 <= n100 <= 14:
        return f"{number} кибер-котлет"

    # 2. Если заканчивается на 1 (кроме 11) — 'котлета' (1 котлета, 21 котлета, 101 котлета)
    if n10 == 1:
        return f"{number} кибер-котлета"

    # 3. Если заканчивается на 2, 3, 4 — 'котлеты' (2 котлеты, 33 котлеты, 54 котлеты)
    if 2 <= n10 == 4:
        return f"{number} кибер-котлеты"

    # 4. Все остальные варианты — 'котлет' (0 котлет, 5 котлет, 10 котлет, 20 котлет)
    return f"{number} кибер-котлет"
