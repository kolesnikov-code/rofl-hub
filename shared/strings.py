def get_plural_cutlets(number: int) -> str:
    """
    Снайперский офис плюрализации Анатолия Алексеевича.
    Хладнокровно подставляет правильное окончание к слову 'котлета'
    на основе остатка от деления числа на 10 и 100.
    """
    # Берем модуль числа на случай отрицательных проверок аналитики
    n = abs(number)

    # Находим остатки от деления на 100 и на 10
    n100 = n % 100
    n10 = n % 10

    # 1. Жесткое исключение русского языка: от 11 до 14 всегда 'кибер-котлет'
    if 11 <= n100 <= 14:
        return f"{number} кибер-котлет"

    # 2. Если заканчивается на 1 (кроме 11) — 'кибер-котлета'
    if n10 == 1:
        return f"{number} кибер-котлета"

    # 3. ТИТАНОВОЕ ИСПРАВЛЕНИЕ: диапазон от 2 до 4 включительно!
    if 2 <= n10 <= 4:
        return f"{number} кибер-котлены"

    # 4. Все остальные варианты — 'кибер-котлет' (0, 5, 10, 20 и т.д.)
    return f"{number} кибер-котлет"
