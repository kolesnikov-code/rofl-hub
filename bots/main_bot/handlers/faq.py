import logging
from aiogram import Router, types, F
from aiogram.filters import Command

router = Router()
logger = logging.getLogger(__name__)

def get_faq_keyboard() -> types.InlineKeyboardMarkup:
    """Вспомогательная функция сборки кнопок быстрого перехода из FAQ"""
    return types.InlineKeyboardMarkup(inline_keyboard=[
        [
            types.InlineKeyboardButton(text="💿 Главное Меню /menu", callback_data="back_to_shop_fake"),
            types.InlineKeyboardButton(text="🏪 Открыть Магазин /shop", callback_data="open_shop_from_farm")
        ]
    ])

# ============================================================================
# 📚 ОБРАБОТЧИК КОМАНДЫ /FAQ
# ============================================================================
@router.message(Command("faq"))
async def cmd_faq_screen(message: types.Message):
    """
    Выводит сухие, четкие и лаконичные ответы на самые популярные вопросы
    подростков строго по утвержденной токеномике Анатолия Алексеевича.
    """
    faq_text = (
        "📚 <b>СПРАВОЧНИК ЧАСТО ЗАДАВАЕМЫХ ВОПРОСОВ (FAQ)</b>\n"
        "..................................................\n\n"
        "❓ <b>Как работает автоматический майнинг монет?</b>\n"
        "• Каждая целая котлета, заправленная в Холодильник, дает твоим роботам топливо на 24 часа работы. "
        "Младший Майнер приносит строго <b>2 монеты в час</b>, а Кибер-Бурильщик — строго <b>5 монет в час</b>.\n\n"
        "❓ <b>What произойдет, если я вовремя не покормлю роботов?</b>\n"
        "• Роботы разрядятся, и добыча валюты полностью остановится до тех пор, пока ты не зайдешь в меню /farm, "
        "не заправишь склад и не нажмешь кнопку запуска.\n\n"
        "❓ <b>Зачем нужен ремонт в Мастерской?</b>\n"
        "• Кибер-Бурильщики работают на износ. Раз в 30 дней их лицензия истекает, и они ломаются. "
        "Тебе нужно зайти в /shop ➡️ Мастерская и продлить срок их службы за Telegram Stars.\n\n"
        "❓ <b>Как получить 1 000 рофлов за приглашенного друга?</b>\n"
        "• Твой друг должен зарегистрироваться по твоей ссылке и проявить активность — накопить и съесть минимум 3 котлеты "
        "(включаются как бесплатные суточные, так и покупные паки из магазина). После этого бонус зачислится автоматически.\n\n"
        "❓ <b>Зачем создавать команду (банду)?</b>\n"
        "• Команды с лимитом до 50 человек позволяют объединяться с одноклассниками, копить общий рейтинг и участвовать "
        "в массовых тотализаторах и турнирах за призы от администрации!\n"
        "..................................................\n"
        "👇 <b>ИСПОЛЬЗУЙ КНОПКИ ДЛЯ БЫСТРОГО ПЕРЕХОДА ИЗ СПРАВКИ:</b>"
    )
    await message.answer(faq_text, reply_markup=get_faq_keyboard(), parse_mode="HTML")

@router.callback_query(F.data == "back_to_shop_fake")
async def back_to_shop_fake_callback(callback: types.CallbackQuery):
    await callback.answer()
    await callback.message.delete()
    await callback.message.answer("💿 Напиши команду /menu, чтобы открыть полный список доступных разделов.")
