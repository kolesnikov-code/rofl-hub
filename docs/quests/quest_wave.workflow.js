export const meta = {
  name: 'quest-wave',
  description: 'Заход банка квестов ROFL HUB: каркас → критика → автор → 4 проверки → правки → финальная приёмка',
  phases: [
    { title: 'Каркас', detail: 'идея, поворот, улики, карта сцен' },
    { title: 'Критика каркаса', detail: 'логика/честная игра и драматургия/оригинальность' },
    { title: 'Доработка каркаса' },
    { title: 'Написание', detail: 'JSON в data/quests' },
    { title: 'Проверка', detail: 'логика, язык и юмор, слепой плейтест, правила' },
    { title: 'Правки' },
    { title: 'Финал' },
  ],
}

const REPO = 'C:/Users/user/PycharmProjects/ROFL-HUB/.claude/worktrees/claude-md-block-2-9ceca3'
const BRIEF = `Сначала прочитай целиком ${REPO}/docs/quests/BRIEF.md и выполни всё, что он требует прочитать (FRAMEWORKS.md, LOCALIZATION.md, докстринг quest_loader.py, образцы forty_candles.json и golden_cutlet.json). Все правила брифа обязательны. Пиши по-русски.`

const SLOTS = args.slots   // [{id, order, slot}] — жанры захода (docs/quests/QUEUE.md)

const OUTLINE = { type: 'object', properties: { title: { type: 'string' }, outline: { type: 'string' } }, required: ['title', 'outline'] }
const CRIT = { type: 'object', properties: { score: { type: 'number' }, must_fix: { type: 'array', items: { type: 'string' } }, ideas: { type: 'array', items: { type: 'string' } } }, required: ['score', 'must_fix', 'ideas'] }
const DONE = { type: 'object', properties: { valid: { type: 'boolean' }, scenes: { type: 'number' }, summary: { type: 'string' } }, required: ['valid', 'summary'] }
const REVIEW = { type: 'object', properties: { verdict: { type: 'string' }, must_fix: { type: 'array', items: { type: 'string' } }, nice: { type: 'array', items: { type: 'string' } } }, required: ['verdict', 'must_fix', 'nice'] }
const FINAL = { type: 'object', properties: { pass: { type: 'boolean' }, rating: { type: 'number' }, issues: { type: 'array', items: { type: 'string' } }, summary: { type: 'string' } }, required: ['pass', 'rating', 'issues', 'summary'] }

const others = s => SLOTS.filter(x => x.id !== s.id).map(x => x.slot.split(':')[0]).join('; ')
const file = s => `${REPO}/data/quests/${s.id}.json`

const REVIEWERS = [
  { key: 'logic', lens: 'ЛОГИКА И ЧЕСТНАЯ ИГРА. Пройди граф сцен (флаги need/missing/set, input, timer): нет ли тупиков, недостижимых улик, дыр во времени и мотивах; каждого невиновного исключает явный факт; разгадку можно вывести логикой из доступного игроку до развязки; ответы input честно решаемы из текста и в answers есть все разумные варианты написания; таймеры не ставятся на сцены с длинным текстом.' },
  { key: 'style', lens: 'ЯЗЫК, РИТМ, ЮМОР. Живой русский язык, диалоги звучат как люди, нет канцелярита и штампов, сцены не затянуты, напряжение растёт к развязке. Доза юмора по брифу (1–10% вне комедии; в комедии — смешно вслух и без пошлости). Гендерно-нейтральное обращение к игроку, без Title Case, 🪙 при числах, без слова «рофл». Укажи конкретные фразы и как переписать.' },
  { key: 'playtest', lens: 'СЛЕПОЙ ПЛЕЙТЕСТ. Не читай концовки заранее. Пройди квест как игрок: от start, читая только текущую сцену и выбирая кнопки, минимум 3 разными путями (любопытный, торопливый, ошибающийся). Записывай ощущения: где скучно, где догадался(лась) слишком рано, где запутался(лась), где перехватило дух, где смешно, какие кнопки непонятны, не слишком ли жёсткий таймер. Только потом сверься с полным файлом.' },
  { key: 'rules', lens: 'ПРАВИЛА И БЕЗОПАСНОСТЬ. Сверь файл со ВСЕМИ пунктами BRIEF.md и LOCALIZATION.md: 14+, запретные темы, имена (запрет «Нина», «Савелий», «Савельевна»; без реальных людей и брендов), провалы без спойлеров + приглашение пройти снова, подписи кнопок без подсказок, «⬅️ К персонажу», who/annoyed у персонажей, атмосферы существуют в fx.js и уместны (хоррор-эффекты не в комедии, зеркало только где стекло), награда и цена подсказок, длины ключей. Плюс ОРИГИНАЛЬНОСТЬ: не пересказ фильма, имена/реплики свои.' },
]

const results = await pipeline(
  SLOTS,
  // 1. Каркас
  s => agent(`${BRIEF}

Задание: придумай КАРКАС одного квеста для банка ROFL HUB.
Слот: ${s.slot}
id квеста: ${s.id}, order: ${s.order}. Параллельно другие авторы делают: ${others(s)} — не пересекайся с ними по сюжету.
Посмотри существующие квесты в data/quests/ — не повторяй их идеи.

Выдай подробный каркас (outline): название; какой каркас/комбинация из FRAMEWORKS.md и что в нём своё; завязка; персонажи (имя, роль, мотив, характер, речевая манера); тайна и полная разгадка; поворот(ы) и какими деталями они подготовлены; карта улик (где найти, что доказывает, кого исключает); карта сцен (ключ, назначение, выборы и флаги need/missing/set; где input с ответами, где timer); тупики с юмором; концовки (победа/провалы, без спойлеров в провалах); 3–5 конкретных юмористических/жутких/напряжённых моментов-«крючков». Ничего не записывай в файлы.`,
    { label: `каркас:${s.id}`, phase: 'Каркас', schema: OUTLINE }),
  // 2. Две критики параллельно → 3. Доработка
  (o, s) => parallel([
    () => agent(`${BRIEF}

Ты — жёсткий критик ЛОГИКИ и ЧЕСТНОЙ ИГРЫ. Найди всё, что сломает квест: разгадку нельзя вывести, невиновный не исключён, улика недостижима, поворот не подготовлен или притянут, шифр нерешаем или решается угадыванием, дыры во времени. По умолчанию будь скептичен.
Слот: ${s.slot}
Каркас «${o.title}»:
${o.outline}`, { label: `критика-логика:${s.id}`, phase: 'Критика каркаса', schema: CRIT }),
    () => agent(`${BRIEF}

Ты — жёсткий критик ДРАМАТУРГИИ и ОРИГИНАЛЬНОСТИ (редактор, который отклонил сотню сценариев). Оцени по шкале 1–10: захватывает ли с первой сцены, растёт ли напряжение, «перехватит ли дух» у развязки, смешно ли там, где задумано смешно, не вторичен ли сюжет, живые ли персонажи. Предложи конкретные усиления (сильнее поворот, лучше крючок, смешнее реплика). По умолчанию будь скептичен.
Слот: ${s.slot}
Каркас «${o.title}»:
${o.outline}`, { label: `критика-драма:${s.id}`, phase: 'Критика каркаса', schema: CRIT }),
  ]).then(cs => agent(`${BRIEF}

Ты — автор каркаса. Перепиши каркас, устранив ВСЕ must_fix обеих критик и взяв лучшие идеи (если с чем-то не согласен(на) — объясни в одной строке в конце). Сохрани полный формат каркаса.
Слот: ${s.slot}
Исходный каркас «${o.title}»:
${o.outline}

Критика логики: ${JSON.stringify(cs[0])}
Критика драматургии: ${JSON.stringify(cs[1])}`, { label: `доработка:${s.id}`, phase: 'Доработка каркаса', schema: OUTLINE })),
  // 4. Написание
  (o, s) => agent(`${BRIEF}

Напиши квест по каркасу целиком в файл ${file(s)} (id "${s.id}", order ${s.order}). Это финальный художественный текст — пиши как лучший автор интерактивных историй: каждая сцена сильная, без воды, с атмосферой (mood) к месту. Соблюдай формат и все правила брифа. После записи прогони валидацию из раздела «Проверка» брифа и исправь все ошибки своего файла (тест test_all_quests_loaded_in_order может падать из-за новых файлов — это нормально, его не трогай). Чужие файлы не трогай.
Слот: ${s.slot}
Каркас «${o.title}»:
${o.outline}`, { label: `автор:${s.id}`, phase: 'Написание', schema: DONE }).then(r => ({ outline: o, author: r })),
  // 5. Проверки параллельно → 6. Правки
  (w, s) => parallel(REVIEWERS.map(rv => () => agent(`${BRIEF}

Ты — проверяющий квеста ${file(s)}. Твоя линза: ${rv.lens}
Не правь файл — только отчёт. must_fix — то, без чего квест нельзя выпускать (с конкретикой: сцена, фраза, что сделать); nice — улучшения. Будь требователен: владелец хочет шедевр.
Слот: ${s.slot}`, { label: `${rv.key}:${s.id}`, phase: 'Проверка', schema: REVIEW })))
    .then(rs => agent(`${BRIEF}

Ты — автор квеста ${file(s)}. Исправь ВСЕ must_fix из отчётов проверяющих и внеси улучшения из nice, которые делают квест сильнее (не раздувай текст). Если два замечания противоречат — выбери вариант, лучший для игрока, и объясни в summary. После правок прогони валидацию из брифа, файл должен быть валиден, победа достижима.
Отчёты:
${rs.filter(Boolean).map((r, i) => REVIEWERS[i].key + ': ' + JSON.stringify(r)).join('\n\n')}`, { label: `правки:${s.id}`, phase: 'Правки', schema: DONE })),
  // 7. Финальная проверка
  (f, s) => agent(`${BRIEF}

Финальная приёмка квеста ${file(s)}. Прогони валидацию из брифа. Прочитай квест целиком как редактор, выпускающий в печать: ни одного ляпа в логике, языке, правилах. Мелкие опечатки и мелкие нарушения правил исправь сам прямо в файле (и снова прогони валидацию). Если есть серьёзная проблема, которую нельзя быстро исправить, — pass=false и опиши. rating — твоя честная оценка квеста 1–10 для владельца, summary — 3–4 предложения: о чём квест, чем цепляет, какой поворот (без раскрытия разгадки), длина.`,
    { label: `финал:${s.id}`, phase: 'Финал', schema: FINAL }).then(r => ({ id: s.id, ...r })),
)
return results.filter(Boolean)
